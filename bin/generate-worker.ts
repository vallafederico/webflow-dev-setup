import { existsSync } from "node:fs";
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";

export const WORKER_FILE = join(".generated", "worker.ts");

/** The router answers only these. `Object.hasOwn` alone would let a module export named `constructor` through. */
const METHODS = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"];

/** Top-level `api/*.ts`, the same files `bin/api.ts` serves. Subfolders hold shared helpers. */
export async function listApiRoutes(apiDir: string): Promise<string[]> {
  if (!existsSync(apiDir)) return [];
  const entries = await readdir(apiDir, { withFileTypes: true });
  return entries
    .filter((e) => e.isFile() && e.name.endsWith(".ts") && !e.name.endsWith(".d.ts"))
    .map((e) => e.name.slice(0, -".ts".length))
    .sort();
}

/** `importDir` is where the generated file lives relative to `api/`, so imports resolve from `.generated/`. */
export function generateWorkerSource(routes: string[], importDir: string): string {
  const imports = routes
    .map((name, i) => `import * as route${i} from ${JSON.stringify(`${importDir}/${name}`)};`)
    .join("\n");
  const table = routes
    .map((name, i) => `  ${JSON.stringify(`/api/${name}`)}: route${i},`)
    .join("\n");

  return `// Generated by bin/generate-worker.ts from api/*.ts. Do not edit.
${imports}

type Handler = (request: Request) => Response | Promise<Response>;

const METHODS = ${JSON.stringify(METHODS)};

const routes: Record<string, Record<string, unknown>> = {
${table}
};

const text = (body: string, status: number, headers?: Record<string, string>) =>
  new Response(body, { status, headers });

export default {
  async fetch(request: Request): Promise<Response> {
    // Requests for missing assets reach the Worker too.
    const { pathname } = new URL(request.url);
    if (!pathname.startsWith("/api/") || !Object.hasOwn(routes, pathname)) {
      return text("Not Found", 404);
    }

    const route = routes[pathname];
    const allowed = METHODS.filter(
      (m) => Object.hasOwn(route, m) && typeof route[m] === "function"
    );
    if (!allowed.includes(request.method)) {
      return text(\`Method \${request.method} not allowed\`, 405, {
        Allow: allowed.join(", "),
      });
    }

    try {
      return await (route[request.method] as Handler)(request);
    } catch (error) {
      console.error(\`\${request.method} \${pathname} failed:\`, error);
      return text("Internal Server Error", 500);
    }
  },
};
`;
}

/** Writes `.generated/worker.ts` under `cwd` and returns its path. */
export async function generateWorker(cwd = process.cwd()): Promise<string> {
  const apiDir = resolve(cwd, "api");
  const outFile = resolve(cwd, WORKER_FILE);
  const importDir = relative(join(outFile, ".."), apiDir).split(sep).join("/");

  const routes = await listApiRoutes(apiDir);
  await mkdir(join(outFile, ".."), { recursive: true });
  await writeFile(outFile, generateWorkerSource(routes, importDir));
  return outFile;
}

if (import.meta.main) {
  const file = await generateWorker();
  console.log(`⚙️  Worker router written to ${file}`);
}
